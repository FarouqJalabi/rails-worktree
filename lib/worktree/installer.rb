require "fileutils"
require "open3"

module RailsWorktree
  # Installs the launcher and the repository integration files:
  # .gitignore entry, .worktree.yml, .worktreeinclude (Claude Code), the
  # AGENTS.md / CLAUDE.md block and the herdr plugin under .worktree/herdr.
  class Installer
    AGENTS_START = "<!-- rails-worktree:start -->".freeze
    AGENTS_FINISH = "<!-- rails-worktree:end -->".freeze
    INCLUDE_START = "# rails-worktree:start".freeze
    INCLUDE_FINISH = "# rails-worktree:end".freeze
    HERDR_DIR = ".worktree/herdr".freeze

    def self.install(root, replace: false, quiet: true)
      new(root, replace: replace, quiet: quiet).install
    end

    def self.ignore_worktrees(root)
      new(root).ignore_worktrees
    end

    def initialize(root, replace: false, quiet: true)
      @root = File.expand_path(root)
      @replace = replace
      @quiet = quiet
      @changes = []
    end

    def install
      Launcher.install(@root, replace: @replace)
      ignore_worktrees
      write_config
      write_worktreeinclude
      write_agents_block
      write_herdr_plugin
      report
      @changes
    end

    def ignore_worktrees
      path = File.join(@root, ".gitignore")
      content = File.exist?(path) ? File.read(path) : ""
      return if content.lines.any? { |line| %w[ .worktrees .worktrees/ /.worktrees /.worktrees/ ].include?(line.strip) }

      File.open(path, "a") do |file|
        file.puts unless content.empty? || content.end_with?("\n")
        file.puts "/.worktrees/"
      end
      @changes << ".gitignore"
    end

    private

    def config
      @config ||= Config.load(@root)
    end

    def write_config
      path = File.join(@root, Config::FILE)
      return if File.exist?(path)

      File.write(path, Config::TEMPLATE)
      @changes << Config::FILE
    end

    def write_worktreeinclude
      body = ["# Gitignored files Claude Code copies into every worktree it creates.",
        "# Generated from the copy list in #{Config::FILE}; rerun bin/worktree install to update."] + config.copy_patterns
      @changes << ".worktreeinclude" if ManagedBlock.write(File.join(@root, ".worktreeinclude"), body.join("\n"), start: INCLUDE_START, finish: INCLUDE_FINISH)
    end

    def write_agents_block
      body = <<~MARKDOWN
        ## Worktrees

        A fresh checkout (git worktree, herdr, Claude Code or Codex) has no gitignored
        configuration. Run `bin/worktree init` in it before starting the app or the specs.
        It copies the files listed in `#{Config::FILE}` from the main checkout and is safe to repeat.

        - `bin/worktree init --level minimal`: configuration files only, shares the main development database.
        - `bin/worktree init --level test`: minimal plus an isolated test setup.
        - `bin/worktree init --level full`: minimal plus own development and test databases.
        - `bin/worktree create <name> <base>`: create a worktree under `.worktrees/` and provision it.
      MARKDOWN
      agents_files.each do |path|
        @changes << File.basename(path) if ManagedBlock.write(path, body, start: AGENTS_START, finish: AGENTS_FINISH)
      end
    end

    # AGENTS.md and CLAUDE.md when they exist; a symlink to the other file counts once.
    # Without either file, AGENTS.md is created.
    def agents_files
      candidates = %w[AGENTS.md CLAUDE.md].map { |name| File.join(@root, name) }.select { |path| File.exist?(path) }
      return [File.join(@root, "AGENTS.md")] if candidates.empty?

      candidates.uniq { |path| File.realpath(path) }
    end

    def write_herdr_plugin
      directory = File.join(@root, HERDR_DIR)
      FileUtils.mkdir_p(directory)
      manifest = File.join(directory, "herdr-plugin.toml")
      script = File.join(directory, "provision")
      app = File.basename(main_checkout).gsub(/[^A-Za-z0-9_.-]/, "-")
      manifest_body = <<~TOML
        # herdr plugin generated by rails-worktree. Link it once per machine:
        #   herdr plugin link #{HERDR_DIR}
        # It provisions every worktree herdr creates for this repository.
        id = "rails-worktree.#{app}"
        name = "rails-worktree (#{app})"
        version = "#{VERSION}"
        min_herdr_version = "0.8.0"
        description = "Provision new herdr worktrees with bin/worktree init"
        platforms = ["linux", "macos"]

        [[events]]
        on = "worktree.created"
        command = ["./provision"]
      TOML
      script_body = <<~'SH'
        #!/bin/sh
        # Runs bin/worktree init in the worktree that herdr just created.
        # Skips checkouts of other repositories (no bin/worktree launcher).
        set -eu
        path=$(ruby -rjson -e 'event = JSON.parse(ENV.fetch("HERDR_PLUGIN_EVENT_JSON", "{}")); puts(event.dig("worktree", "path") || event["path"] || "")')
        [ -n "$path" ] || exit 0
        [ -x "$path/bin/worktree" ] || exit 0
        here=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd -P)
        main_of() { git -C "$1" worktree list --porcelain | head -n 1 | sed 's/^worktree //'; }
        [ "$(main_of "$path")" = "$(main_of "$here")" ] || exit 0
        cd "$path"
        exec bin/worktree init --level "${RAILS_WORKTREE_HERDR_LEVEL:-minimal}"
      SH
      write_if_changed(manifest, manifest_body)
      write_if_changed(script, script_body, mode: 0755)
    end

    # The main checkout's directory, so a worktree installs the same plugin id as the main checkout.
    def main_checkout
      output, _error, status = Open3.capture3(Context::GIT_ENVIRONMENT, "git", "-C", @root, "worktree", "list", "--porcelain")
      first = status.success? && output.lines.grep(/^worktree /).first
      first ? first.delete_prefix("worktree ").strip : @root
    end

    def write_if_changed(path, body, mode: nil)
      return if File.file?(path) && File.read(path) == body && (mode.nil? || File.executable?(path))

      File.write(path, body)
      File.chmod(mode, path) if mode
      @changes << path.delete_prefix(@root + File::SEPARATOR)
    end

    def report
      return if @quiet || @changes.empty?

      @changes.each { |change| puts "  wrote #{change}" }
    end
  end
end
